"""Remotion workspace, per-session scaffold and render for Studio mode (Phase 17, FR-STD-06, FR-STD-13).

Layout (verified in spike S11 on Windows, Remotion 4.0.484):
  tools/studio/package.json + node_modules/                shared, installed once
  media/studio/<session>/src/{index.ts,Root.tsx,lib.tsx}   written by the app
  media/studio/<session>/plan.json                         script, written by the agent (or from a template)
  media/studio/<session>/src/plan.ts                       generated by the app from plan.json
  media/studio/<session>/src/Scene.tsx                     presentation, written by the agent
  media/studio/<session>/public/                           footage copies + font
  media/studio/<session>/node_modules                      junction to the shared install
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

from videocreator.paths import REPO_ROOT
from videocreator.pipeline.subtitles import FONTS_DIR

REMOTION_VERSION = "4.0.484"
WORKSPACE_PACKAGE: dict[str, Any] = {
    "name": "videocreator-studio",
    "private": True,
    "dependencies": {
        "@remotion/cli": REMOTION_VERSION,
        "remotion": REMOTION_VERSION,
        "react": "19.2.7",
        "react-dom": "19.2.7",
    },
    "devDependencies": {"@types/react": "19.2.17", "typescript": "6.0.3"},
}

INDEX_TS = """import { registerRoot } from 'remotion';
import { Root } from './Root';

registerRoot(Root);
"""

ROOT_TSX = """import React from 'react';
import { Composition } from 'remotion';
import { FPS, HEIGHT, WIDTH } from './lib';
import { TOTAL_FRAMES } from './plan';
import { Scene } from './Scene';

export const Root: React.FC = () => (
  <Composition id="Main" component={Scene} width={WIDTH} height={HEIGHT} fps={FPS} durationInFrames={TOTAL_FRAMES} />
);
"""

# Product footage is shown untouched: no filter, no opacity, no playbackRate, no cover-crop (BR-PRD-02, BR-PRD-03).
LIB_TSX = """import React from 'react';
import { OffthreadVideo, staticFile } from 'remotion';

export const WIDTH = 1080;
export const HEIGHT = 1920;
export const FPS = 30;
export const SAFE = { top: __SAFE_TOP__, bottom: __SAFE_BOTTOM__, right: __SAFE_RIGHT__ };
export const FONT_FAMILY = 'Be Vietnam Pro';

export const sec = (seconds: number): number => Math.round(seconds * FPS);

export const FontFace: React.FC = () => (
  <style>{`@font-face { font-family: '${FONT_FAMILY}'; font-weight: 700; src: url('${staticFile('BeVietnamPro-Bold.ttf')}') format('truetype'); }`}</style>
);

export const ProductShot: React.FC<{ file: string; startS: number }> = ({ file, startS }) => (
  <OffthreadVideo
    src={staticFile(file)}
    startFrom={sec(startS)}
    muted
    style={{ position: 'absolute', left: 0, top: 0, width: WIDTH, height: HEIGHT, objectFit: 'contain' }}
  />
);

export const Subtitle: React.FC<{ text: string; style?: React.CSSProperties }> = ({ text, style }) => (
  <div
    style={{
      position: 'absolute',
      left: 60,
      right: Math.round(WIDTH * SAFE.right),
      bottom: Math.round(HEIGHT * SAFE.bottom),
      textAlign: 'center',
      fontFamily: `'${FONT_FAMILY}'`,
      fontWeight: 700,
      fontSize: 56,
      lineHeight: 1.25,
      color: '#fff',
      textShadow: '0 0 6px #000, 0 2px 4px #000, 0 0 2px #000',
      ...style,
    }}
  >
    {text}
  </div>
);
"""

REMOTION_CONFIG_TS = """import { Config } from '@remotion/cli/config';

Config.setVideoImageFormat('jpeg');
Config.setOverwriteOutput(true);
Config.setChromiumOpenGlRenderer('angle');
Config.setConcurrency(2);
"""

TSCONFIG_JSON = """{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "jsx": "react-jsx",
    "strict": true,
    "skipLibCheck": true,
    "esModuleInterop": true,
    "noEmit": true,
    "lib": ["DOM", "ES2022"]
  },
  "include": ["src"]
}
"""


class StudioEnvError(RuntimeError):
    """Node.js or the Remotion workspace is missing or failed to install."""


class StudioRenderError(RuntimeError):
    """`remotion render` failed; the message carries the tail of its output."""


def _node() -> str:
    node = shutil.which("node")
    if not node:
        raise StudioEnvError("Chưa cài Node.js; chế độ Studio cần Node.js LTS.")
    return node


def workspace_dir() -> Path:
    return REPO_ROOT / "tools" / "studio"


def _cli() -> Path:
    return workspace_dir() / "node_modules" / "@remotion" / "cli" / "remotion-cli.js"


def _browser() -> Path | None:
    """The headless browser Remotion downloaded into the shared workspace (one copy for all sessions)."""
    found = sorted((workspace_dir() / "node_modules" / ".remotion").glob("chrome-headless-shell/*/*/chrome-headless-shell*"))
    return next((p for p in found if p.is_file()), None)


def workspace_ready() -> bool:
    return _cli().exists() and _browser() is not None


def _link_node_modules(session_dir: Path) -> None:
    link = session_dir / "node_modules"
    if link.exists():
        return
    target = workspace_dir() / "node_modules"
    if os.name == "nt":
        import _winapi

        _winapi.CreateJunction(str(target), str(link))
    else:
        os.symlink(target, link, target_is_directory=True)


def ensure_workspace(*, timeout_s: int = 900) -> None:
    """Installs the pinned Remotion workspace on first use (FR-STD-13)."""
    _node()
    if workspace_ready():
        return
    studio_root = workspace_dir()
    npm = shutil.which("npm")
    if not npm:
        raise StudioEnvError("Không tìm thấy npm để cài Remotion.")
    studio_root.mkdir(parents=True, exist_ok=True)
    (studio_root / "package.json").write_text(json.dumps(WORKSPACE_PACKAGE, indent=2), encoding="utf-8")
    proc = subprocess.run(
        [npm, "install", "--no-audit", "--no-fund"],
        cwd=studio_root, capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=timeout_s, stdin=subprocess.DEVNULL, shell=False,
    )
    if proc.returncode == 0 and _cli().exists():
        proc = subprocess.run(
            [_node(), str(_cli()), "browser", "ensure"],
            cwd=studio_root, capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout_s, stdin=subprocess.DEVNULL,
        )
    if proc.returncode != 0 or not workspace_ready():
        raise StudioEnvError(f"Cài Remotion thất bại: {(proc.stderr or proc.stdout)[-600:]}")


def scaffold_session(
    session_dir: Path,
    *,
    footage_files: dict[str, Path],
    brief: dict[str, Any],
    safe_zone: tuple[float, float, float],
) -> None:
    """Writes the app-owned files of a session; `src/Scene.tsx` is left to the agent."""
    src_dir = session_dir / "src"
    public_dir = session_dir / "public"
    src_dir.mkdir(parents=True, exist_ok=True)
    public_dir.mkdir(parents=True, exist_ok=True)
    top, bottom, right = safe_zone
    lib = LIB_TSX.replace("__SAFE_TOP__", str(top)).replace("__SAFE_BOTTOM__", str(bottom)).replace("__SAFE_RIGHT__", str(right))
    (src_dir / "index.ts").write_text(INDEX_TS, encoding="utf-8")
    (src_dir / "Root.tsx").write_text(ROOT_TSX, encoding="utf-8")
    (src_dir / "lib.tsx").write_text(lib, encoding="utf-8")
    (session_dir / "remotion.config.ts").write_text(REMOTION_CONFIG_TS, encoding="utf-8")
    (session_dir / "tsconfig.json").write_text(TSCONFIG_JSON, encoding="utf-8")
    shutil.copy2(FONTS_DIR / "BeVietnamPro-Bold.ttf", public_dir / "BeVietnamPro-Bold.ttf")
    for name, source in footage_files.items():
        dest = public_dir / name
        if not dest.exists() or dest.stat().st_size != source.stat().st_size:
            shutil.copy2(source, dest)
    _link_node_modules(session_dir)
    (session_dir / "brief.json").write_text(json.dumps(brief, ensure_ascii=False, indent=2), encoding="utf-8")


def render_session(session_dir: Path, out_path: Path, *, timeout_s: int = 1800) -> None:
    """Runs `remotion render src/index.ts Main <out>` for the session with the shared workspace CLI."""
    out_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        proc = subprocess.run(
            [_node(), str(_cli()), "render", "src/index.ts", "Main", str(out_path), "--log=error", f"--browser-executable={_browser()}"],
            cwd=session_dir, capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout_s, stdin=subprocess.DEVNULL, env={**os.environ, "CI": "1"},
        )
    except subprocess.TimeoutExpired as exc:
        raise StudioRenderError(f"remotion render quá {timeout_s} giây") from exc
    if proc.returncode != 0 or not out_path.exists():
        raise StudioRenderError(((proc.stderr or "") + (proc.stdout or "")).strip()[-1500:])
