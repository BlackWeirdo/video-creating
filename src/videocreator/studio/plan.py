"""Studio script (`plan.json`): the content of the video, written by the agent, checked by the app.

The script is what the user confirms (`FR-STD-05`). The app turns it into `src/plan.ts`, the only
place the scene code may take footage files, time ranges and wording from. That keeps the time
ranges checkable and lets a saved scene be re-rendered with new shots and text (`FR-STD-09`).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

FPS = 30
MIN_SCENE_S = 0.7
MIN_TOTAL_S = 3.0
MAX_TOTAL_S = 90.0
MAX_TEXT_CHARS = 90
RANGE_TOLERANCE_S = 0.05


def load_plan(session_dir: Path) -> tuple[dict[str, Any] | None, list[str]]:
    """Reads `plan.json`; returns `(plan, problems)`."""
    plan_file = session_dir / "plan.json"
    if not plan_file.exists():
        return None, ["plan.json chưa được tạo"]
    try:
        plan = json.loads(plan_file.read_text(encoding="utf-8-sig"))
    except ValueError as exc:
        return None, [f"plan.json không phải JSON hợp lệ: {exc}"]
    if not isinstance(plan, dict) or not isinstance(plan.get("scenes"), list):
        return None, ["plan.json phải là object có mảng `scenes`"]
    return plan, []


def validate_plan(plan: dict[str, Any], brief: dict[str, Any]) -> tuple[list[dict[str, Any]], list[str]]:
    """Checks every scene against the shots of the brief. Returns `(normalized_scenes, problems)`."""
    shots = {int(s["shot_id"]): s for s in brief.get("shots", [])}
    products = {int(p["id"]): p for p in brief.get("products", [])}
    scenes: list[dict[str, Any]] = []
    problems: list[str] = []
    if not plan["scenes"]:
        return [], ["plan.json: `scenes` đang rỗng"]

    from_frame = 0
    for idx, raw in enumerate(plan["scenes"], start=1):
        if not isinstance(raw, dict):
            problems.append(f"cảnh {idx}: phải là object")
            continue
        try:
            shot_id = int(raw.get("shot_id"))
            start_s = float(raw.get("start_s"))
            duration_s = float(raw.get("duration_s"))
        except (TypeError, ValueError):
            problems.append(f"cảnh {idx}: thiếu hoặc sai kiểu `shot_id`, `start_s`, `duration_s`")
            continue
        text = str(raw.get("text") or "").strip()
        shot = shots.get(shot_id)
        if shot is None:
            problems.append(f"cảnh {idx}: shot_id={shot_id} không có trong brief.json")
            continue
        s_start, s_end = float(shot["start_s"]), float(shot["end_s"])
        if start_s < s_start - RANGE_TOLERANCE_S or start_s + duration_s > s_end + RANGE_TOLERANCE_S:
            problems.append(
                f"cảnh {idx}: khoảng {start_s:.2f}-{start_s + duration_s:.2f}s nằm ngoài shot {shot_id} ({s_start:.2f}-{s_end:.2f}s)"
            )
        if duration_s < MIN_SCENE_S:
            problems.append(f"cảnh {idx}: thời lượng {duration_s:.2f}s ngắn hơn {MIN_SCENE_S}s")
        if len(text) > MAX_TEXT_CHARS:
            problems.append(f"cảnh {idx}: phụ đề dài {len(text)} ký tự (tối đa {MAX_TEXT_CHARS})")
        # BR-PRD-05: a line must not name a product that is not in its shot.
        shot_pids = set(shot.get("product_ids") or [])
        for pid, prod in products.items():
            name = str(prod.get("name") or "").strip().lower()
            if shot_pids and pid not in shot_pids and len(name) >= 4 and name in text.lower():
                problems.append(f"cảnh {idx}: phụ đề nhắc sản phẩm '{prod['name']}' không có trong shot {shot_id}")
        frames = max(1, round(duration_s * FPS))
        scenes.append(
            {
                "shot_id": shot_id,
                "file": str(shot["file"]),
                "start_s": round(start_s, 3),
                "duration_s": round(frames / FPS, 3),
                "text": text,
                "from_frame": from_frame,
                "duration_frames": frames,
                "product_ids": sorted(shot_pids),
            }
        )
        from_frame += frames

    total_s = from_frame / FPS
    if scenes and not problems and not (MIN_TOTAL_S <= total_s <= MAX_TOTAL_S):
        problems.append(f"tổng thời lượng {total_s:.1f}s nằm ngoài khoảng {MIN_TOTAL_S:.0f}-{MAX_TOTAL_S:.0f}s")
    return scenes, problems


def write_plan_ts(session_dir: Path, title: str, scenes: list[dict[str, Any]]) -> None:
    """Writes the app-owned `src/plan.ts` the scene code reads its content from."""
    data = {
        "title": title,
        "scenes": [
            {
                "file": s["file"],
                "startS": s["start_s"],
                "fromFrame": s["from_frame"],
                "durationFrames": s["duration_frames"],
                "text": s["text"],
            }
            for s in scenes
        ],
    }
    total = sum(int(s["duration_frames"]) for s in scenes)
    body = (
        "// Generated by the app from plan.json. Do not edit.\n"
        "export type PlanScene = { file: string; startS: number; fromFrame: number; durationFrames: number; text: string };\n"
        f"export const PLAN: {{ title: string; scenes: PlanScene[] }} = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
        f"export const TOTAL_FRAMES = {total};\n"
    )
    (session_dir / "src" / "plan.ts").write_text(body, encoding="utf-8")


def extract_plan_captions(plan: dict[str, Any] | None) -> dict[str, dict[str, Any]]:
    """Extracts and sanitizes optional 4-platform captions written into `plan.json` (`BR-CAP-01`)."""
    from videocreator.pipeline.caption_limits import CAPTION_PLATFORMS, clean_caption

    if not isinstance(plan, dict):
        return {}
    raw_caps = plan.get("captions")
    if not isinstance(raw_caps, dict):
        return {}
    out: dict[str, dict[str, Any]] = {}
    for platform in CAPTION_PLATFORMS:
        entry = raw_caps.get(platform)
        if isinstance(entry, dict):
            text = str(entry.get("text") or "").strip()
            tags = [str(t) for t in (entry.get("hashtags") or []) if str(t).strip()]
            if text:
                out[platform] = clean_caption(platform, text, tags)
        elif isinstance(entry, str) and entry.strip():
            out[platform] = clean_caption(platform, entry.strip(), [])
    return out


def build_fallback_captions(title: str, scenes: list[dict[str, Any]], *, caption_lang: str = "vi") -> dict[str, dict[str, Any]]:
    """Generates safe, fact-free craft captions when a trend-driven Studio session omitted captions."""
    from videocreator.pipeline.caption_limits import CAPTION_PLATFORMS, clean_caption

    lines = [str(s.get("text") or "").strip() for s in scenes if str(s.get("text") or "").strip()]
    lead = lines[0] if lines else title
    if caption_lang == "en":
        body = f"{lead} — Handcrafted artisan jewelry."
        base_tags = ["handcraftedjewelry", "silvercraft", "artisanjewelry", "jewelrymaking"]
    else:
        body = f"{lead} — Chế tác trang sức thủ công tỉ mỉ từng chi tiết."
        base_tags = ["trangsucbac", "chetacthucong", "bacmynghe", "handmadejewelry"]
    return {
        platform: clean_caption(platform, body, base_tags[:1] if platform == "threads" else base_tags)
        for platform in CAPTION_PLATFORMS
    }


def video_plan_json(
    title: str,
    scenes: list[dict[str, Any]],
    *,
    voice_lang: str,
    unverified_claims: list[str],
    formula: str = "studio-custom",
    captions: dict[str, dict[str, Any]] | None = None,
    trend_analysis: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Same shape as a Fast mode plan, so the approval screen shows Studio videos the same way."""
    out: dict[str, Any] = {
        "formula": formula.strip() or "studio-custom",
        "title": title,
        "voice_lang": voice_lang,
        "product_ids": sorted({pid for s in scenes for pid in s["product_ids"]}),
        "total_duration_s": round(sum(s["duration_s"] for s in scenes), 2),
        "shots": [
            {"shot_id": s["shot_id"], "start_s": s["start_s"], "duration_s": s["duration_s"], "text": s["text"]}
            for s in scenes
        ],
        "unverified_claims": unverified_claims,
    }
    if captions:
        out["captions"] = captions
    if trend_analysis:
        out["trend_analysis"] = trend_analysis
    return out
